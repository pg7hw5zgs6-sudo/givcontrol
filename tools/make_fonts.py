#!/usr/bin/env python3
"""Generate anti-aliased TFT_eSPI smooth fonts (VLW format) as C arrays in flash.

    python3 tools/make_fonts.py        # writes firmware/src/fonts.h

Fonts: Noto Sans Regular/Bold (SIL Open Font License), in tools/fonts/.
VLW layout (big-endian int32): glyphCount, version 11, size, 0, ascent, descent;
then 7 ints per glyph (unicode, height, width, xAdvance, topExtent, leftExtent, 0);
then each glyph's 8-bit alpha bitmap, row by row.
"""
import os
import struct
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "src", "fonts.h")
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))

FONTS = [  # name, file, pixel size, characters
    ("F_SMALL", "NotoSans-Regular.ttf", 13, ASCII),
    ("F_BODY", "NotoSans-Regular.ttf", 16, ASCII),
    ("F_BOLD", "NotoSans-Bold.ttf", 16, ASCII),
    ("F_MID", "NotoSans-Bold.ttf", 22, ASCII),
    ("F_BIG", "NotoSans-Bold.ttf", 46, "0123456789%-?"),
    ("F_TAB", "NotoSans-Bold.ttf", 13, ASCII),
]


# TFT_eSPI blends edges linearly in the panel's (gamma-encoded) colour space, which makes light
# text on a dark fill look thin with dark, coloured fringes. Lift the edge coverage and drop the
# faintest pixels so edges read as clean, slightly heavier strokes.
CURVE = [0 if a < 24 else min(255, round(255 * (a / 255) ** 0.62)) for a in range(256)]


def vlw(path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    metrics, bitmaps = [], []
    for ch in sorted(set(chars + " ")):
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if ch == " " or not w or not h:
            metrics.append((ord(ch), 0, 0, adv, 0, 0, 0))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        metrics.append((ord(ch), h, w, adv, -y0, x0, 0))
        bitmaps.append(bytes(CURVE[a] for a in img.tobytes()))
    out = struct.pack(">6i", len(metrics), 11, size, 0, ascent, descent)
    for m in metrics:
        out += struct.pack(">7i", *m)
    return out + b"".join(bitmaps)


def main():
    lines = ["// Generated by tools/make_fonts.py - do not edit. Noto Sans, SIL Open Font License.",
             "#pragma once", "#include <Arduino.h>", ""]
    total = 0
    for name, file, size, chars in FONTS:
        data = vlw(os.path.join(HERE, "fonts", file), size, chars)
        total += len(data)
        lines.append(f"// {file} {size}px, {len(data)} bytes")
        lines.append(f"static const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {total} bytes of font data")


if __name__ == "__main__":
    main()
